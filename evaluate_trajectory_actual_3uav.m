function avgRate = evaluate_trajectory_actual_3uav( ...
        Q,WS,WP,WW,w_b,w_wifi,H, ...
        f_lic,f_un,f_pbs,f_wifi,c,A2G,n_pbs,n_wifi,Shadow, ...
        P_PBS_j,P_WIFI_m,sigma2_lic,sigma2_un, ...
        GammaLic,GammaUn,Pmax_lic,Pmax_un, ...
        Bsc_lic,Bsc_un,seedBase,nAvg, ...
        useRayleigh,useShadow,useShadowA2G)

N = size(Q,1);

U = size(Q,3);

sumRate = 0;

for n=1:N

    Qslot = zeros(U,3);

    for u=1:U

        Qslot(u,:) = Q(n,:,u);

    end

    sumRate = sumRate + eval_slot_objective_3uav_avg( ...
        Qslot,WS,WP,WW,w_b,w_wifi,H, ...
        f_lic,f_un,f_pbs,f_wifi,c,A2G,n_pbs,n_wifi,Shadow, ...
        P_PBS_j,P_WIFI_m,sigma2_lic,sigma2_un, ...
        GammaLic,GammaUn,Pmax_lic,Pmax_un, ...
        Bsc_lic,Bsc_un,seedBase+n,nAvg, ...
        useRayleigh,useShadow,useShadowA2G);

end

avgRate = sumRate/N;

end
